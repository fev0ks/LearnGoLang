package valid_parentheses

// LeetCode 20. Valid Parentheses (Easy)
// https://leetcode.com/problems/valid-parentheses/
//
// Задача: дана строка из символов '(', ')', '{', '}', '[', ']'. Определить,
// является ли она корректной скобочной последовательностью:
//
//  1. каждая открывающая скобка закрыта скобкой ТОГО ЖЕ типа;
//
//  2. скобки закрываются в правильном порядке (LIFO);
//
//  3. каждая закрывающая скобка имеет соответствующую открывающую.
//
//     "()"      -> true
//     "()[]{}"  -> true
//     "(]"      -> false   (тип не совпал)
//     "([)]"    -> false   (нарушен порядок)
//     "{[]}"    -> true
//
// Идея: стек. Открывающую кладём в стек; на закрывающей проверяем, что на
// вершине лежит парная открывающая. В конце стек должен быть пуст (иначе есть
// незакрытые скобки).
//
// Сложность: O(n) по времени, O(n) по памяти на стек.
func IsValid(s string) bool {
	// Соответствие закрывающая -> ожидаемая открывающая.
	pairs := map[byte]byte{
		')': '(',
		']': '[',
		'}': '{',
	}

	stack := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		c := s[i]
		open, isClosing := pairs[c]
		if !isClosing {
			// Открывающая скобка — кладём в стек.
			stack = append(stack, c)
			continue
		}
		// Закрывающая: на вершине должна лежать парная открывающая.
		if len(stack) == 0 || stack[len(stack)-1] != open {
			return false
		}
		stack = stack[:len(stack)-1]
	}
	// Корректно, только если все открывающие закрыты.
	return len(stack) == 0
}
