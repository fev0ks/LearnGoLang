package sliding_window

// Задача (sliding window): дан массив из положительных чисел. Найти непрерывный
// подмассив с максимальной СУММОЙ, в котором не более двух РАЗЛИЧНЫХ значений.
// Вернуть эту сумму.
//
// Это самостоятельная задача на максимум суммы. Близкий по технике, но другой по
// цели «найти максимальную ДЛИНУ» — это LeetCode 904 Fruit Into Baskets, см.
// ../../leetcode/medium/0904-fruit-into-baskets.
//
//   MaxSum([1, 2])                          == 3   // [1, 2]
//   MaxSum([1, 10, 5, 10, 5, 10, 3, 10, 5]) == 40  // [10, 5, 10, 5, 10]
//   MaxSum([10, 10, 3, 5, 5, 5])            == 23   // [10, 10, 3]
//
// Идея — классическое скользящее окно [left..right]:
//   - расширяем окно вправо, учитывая число различных значений в map'е счётчиков;
//   - как только различных значений стало больше двух, сдвигаем левую границу,
//     пока их снова не станет ≤ 2;
//   - на каждом шаге обновляем максимум суммы окна.
//
// Сложность: O(n) по времени (каждый элемент входит и выходит из окна не более
// одного раза), O(1) по памяти (в map не более трёх ключей).

// MaxSum возвращает максимальную сумму непрерывного подмассива, содержащего не
// более двух различных значений. Предполагаются неотрицательные числа.
func MaxSum(nums []int) int {
	counts := make(map[int]int)
	left, sum, maxSum := 0, 0, 0

	for right := 0; right < len(nums); right++ {
		rightNum := nums[right]
		sum += rightNum
		counts[rightNum]++

		// Слишком много различных значений — ужимаем окно слева.
		for len(counts) > 2 {
			leftNum := nums[left]
			counts[leftNum]--
			sum -= leftNum
			if counts[leftNum] == 0 {
				delete(counts, leftNum)
			}
			left++
		}

		if sum > maxSum {
			maxSum = sum
		}
	}
	return maxSum
}
