package main

import "fmt"

// Дана скобочная последовательность из открывающих и закрывающих скобок.
// Нужно выяснить, можно ли заменой ОДНОЙ скобки (открывающей на закрывающую
// или наоборот) получить правильную последовательность. Если можно — вернуть
// индекс заменяемой скобки, иначе -1.
//
// ((()     -> 1   "()()"
// (((((    -> -1  (нечётная длина — правильной не сделать)
// ())      -> -1
// (((()))( -> 7   "(((())))"
// )()(     -> -1  (счётчики уже равны: одна замена их разбалансирует)
// )(       -> -1
// ((       -> 1   "()"

func main() {
	tests := []string{
		"((()",     // → 1
		"(((((",    // → -1
		"())",      // → -1
		"(((()))(", // → 7
		")()(",     // → -1
		")(",       // → -1
		"((",       // → 1
	}

	for _, test := range tests {
		fmt.Printf("Input: %-10s → Replace index: %d\n", test, findReplaceIndex(test))
	}
}

// findReplaceIndex ищет позицию, замена скобки в которой делает всю
// последовательность правильной. Возвращает первый подходящий индекс или -1.
//
// Прямой и заведомо корректный перебор: пробуем заменить каждую скобку и
// проверяем результат за O(n). Итого O(n^2) — для разбора задачи этого хватает.
func findReplaceIndex(s string) int {
	for i := 0; i < len(s); i++ {
		if isValidAfterFlip(s, i) {
			return i
		}
	}
	return -1
}

// isValidAfterFlip проверяет, станет ли последовательность правильной, если
// заменить символ в позиции i на противоположную скобку.
func isValidAfterFlip(s string, i int) bool {
	balance := 0
	for j := 0; j < len(s); j++ {
		ch := s[j]
		if j == i {
			ch = flip(ch)
		}
		if ch == '(' {
			balance++
		} else {
			balance-- // закрывающая
		}
		if balance < 0 { // закрыли больше, чем открыли — невозможно
			return false
		}
	}
	return balance == 0 // все открытые скобки закрыты
}

func flip(ch byte) byte {
	if ch == '(' {
		return ')'
	}
	return '('
}
